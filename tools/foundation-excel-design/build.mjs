import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { Workbook, SpreadsheetFile, FileBlob } from '@oai/artifact-tool';

const require=createRequire(import.meta.url),here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../..'),X=require(path.join(root,'dist/foundation/excel.js'));
const temp=path.join(here,'tmp'),output=path.join(root,'outputs/01a10fe4-50a3-7050-aee9-2782919acd7d');
await fs.mkdir(temp,{recursive:true});await fs.mkdir(output,{recursive:true});
const packet=JSON.parse(await fs.readFile(path.join(temp,'packet.json'),'utf8'));
const report=X.model(packet),wb=Workbook.create();
for(const s of report.sheets)wb.worksheets.add(s.name);
for(const s of report.sheets){
  const sh=wb.worksheets.getItem(s.name);sh.showGridLines=false;sh.tabColor='#0F766E';
  sh.getRange(`A1:${X.col(s.widths.length-1)}${s.rows.length}`).format=report.styles.text;
  s.widths.forEach((w,i)=>{sh.getRange(`${X.col(i)}:${X.col(i)}`).format.columnWidth=w;});
  for(let i=0;i<s.rows.length;i++){
    const row=s.rows[i];sh.getRange(`A${i+1}:${X.col(s.widths.length-1)}${i+1}`).format.rowHeight=row.height;
    row.cells.forEach((c,j)=>{const range=sh.getRange(X.col(j)+(i+1));range.format=report.styles[c.style];
      if(c.formula)range.formulas=[[c.formula]];else range.values=[[typeof c.v==='string'&&c.v.startsWith('=')?"'"+c.v:c.v]];
    });
  }
  for(const ref of s.merges){sh.mergeCells(ref);const first=ref.split(':')[0],match=first.match(/([A-Z]+)(\d+)/),row=s.rows[Number(match[2])-1];sh.getRange(ref).format=report.styles[row.cells[0].style];}
  if(s.freeze)sh.freezePanes.freezeRows(s.freeze);
}
// Prototype cells give the browser adapter the exact native style IDs authored
// by Artifact Tool. This internal style sheet is omitted from the final export.
const lib=wb.worksheets.add('_서식'),keys=Object.keys(report.styles);
keys.forEach((key,i)=>{const r=lib.getRange('A'+(i+1));r.values=[[key]];r.format=report.styles[key];});
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'요약!A15:F20',include:'values,formulas',tableMaxRows:8,tableMaxCols:6,maxChars:3500})).ndjson);
const template=await SpreadsheetFile.exportXlsx(wb),templatePath=path.join(temp,'design-template.xlsx');await template.save(templatePath);
const python='C:/Users/싸인텔레콤/.cache/codex-runtimes/codex-primary-runtime/dependencies/python/python.exe';
const extraction=JSON.parse(execFileSync(python,['-c',
  'import zipfile,json,sys,xml.etree.ElementTree as E\nwith zipfile.ZipFile(sys.argv[1]) as z:\n s=z.read("xl/styles.xml").decode("utf-8")\n x=E.fromstring(z.read("xl/worksheets/sheet7.xml"))\n ids={int(c.attrib["r"][1:]):int(c.attrib["s"]) for c in x.iter() if c.tag.endswith("}c")}\n print(json.dumps({"styles":s,"ids":ids}))',templatePath],{encoding:'utf8'}));
const theme={styles:extraction.styles,ids:Object.fromEntries(keys.map((k,i)=>[k,extraction.ids[i+1]]))};
if(Object.values(theme.ids).some(v=>v===undefined))throw new Error('Native style ID extraction failed');
const themeJS=`// Generated by tools/foundation-excel-design/build.mjs using Artifact Tool.\n(function(root){const theme=${JSON.stringify(theme)};if(typeof module!=='undefined'&&module.exports)module.exports=theme;else root.FoundationExcelTheme=theme;})(typeof globalThis!=='undefined'?globalThis:this);\n`;
await fs.writeFile(path.join(root,'dist/foundation/excel-theme.js'),themeJS);
const finalPath=path.join(output,'전광판_기초_철근_산출서_예시.xlsx');
await fs.writeFile(finalPath,X.bytes(report,theme));

// Verify the actual offline-generated package, including its cached values and
// formulas, through the public Artifact Tool import/recalculation/render APIs.
const final=await SpreadsheetFile.importXlsx(await FileBlob.load(finalPath));final.recalculate();
console.log((await final.inspect({kind:'table',range:'견적!D27:F29',include:'values,formulas',tableMaxRows:4,tableMaxCols:3,maxChars:2500})).ndjson);
console.log((await final.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!|#N/A',options:{useRegex:true,maxResults:100},maxChars:2000,summary:'Formula errors'})).ndjson);
const summary=final.worksheets.getItem('요약'),cost=final.worksheets.getItem('견적');
const initial=summary.getRange('B20').values[0][0],old=cost.getRange('E9').values[0][0],qty=cost.getRange('D9').values[0][0];
cost.getRange('E9').values=[[old+1000]];final.recalculate();
const changed=summary.getRange('B20').values[0][0],expected=packet.r.estimate.subtotal+Math.round(qty*(old+1000))-Math.round(qty*old);
if(changed!==expected+Math.round(expected*packet.r.p.vat/100))throw new Error(`Rate formula verification failed: ${changed}`);
cost.getRange('E9').values=[[old]];final.recalculate();
if(summary.getRange('B20').values[0][0]!==initial||initial!==packet.r.estimate.total)throw new Error('Summary total mismatch');
for(const s of report.sheets){
  const preview=await final.render({sheetName:s.name,range:`A1:${X.col(s.widths.length-1)}${s.rows.length}`,scale:1,format:'png'});
  await fs.writeFile(path.join(output,`미리보기_${s.name.replace('·','_')}.png`),new Uint8Array(await preview.arrayBuffer()));
  console.log('Rendered '+s.name);
}
await fs.writeFile(path.join(temp,'verification.json'),JSON.stringify({sheets:report.sheets.map(s=>s.name),initialTotal:initial,changedTotal:changed,rateFormulaCheck:true,refs:report.refs},null,2));
console.log(finalPath);
